#!/usr/bin/env python3
"""Bake web/ into src/app/web_assets.h as gzipped PROGMEM blobs.

The GUI has to live in the firmware image: there is no SPIFFS partition worth
the space on the 4 MB C3 build, and a GUI on a filesystem is a second thing to
flash and a second thing to get out of sync. So the browser assets are
compressed here, at build time, and served straight out of flash by
web_server.cpp.

Runs two ways, and must keep working both ways:

  * as a PlatformIO pre-build script (``extra_scripts = pre:tools/...``), where
    SCons hands us an ``env``;
  * as ``python3 firmware/tools/gen_web_assets.py`` from the repo root, for
    regenerating by hand after editing web/ without a full build.

Design rules that matter:

  * mtime 0 in the gzip header, and the header is only rewritten when its
    content actually changes. Otherwise every build would touch web_assets.h
    and force a rebuild of web_server.cpp.
  * A missing web/ directory warns and leaves the committed placeholder alone.
    Bring-up happens long before the GUI exists; a missing GUI must not be a
    build error.

Standard library only, Python 3.9 compatible: it runs inside PlatformIO's own
interpreter, which is whatever the user happens to have.
"""

import argparse
import gzip
import io
import os
import sys

# The one place the asset set is defined. Adding a file to the GUI means adding
# a row here and nothing else: the generator emits the blob, the table row and
# the content type, and web_server.cpp finds it by path.
#
# (source file in web/, C identifier stem, served paths, Content-Type)
ASSETS = [
    ("index.html", "Index", ["/", "/index.html"], "text/html; charset=utf-8"),
    ("app.css", "AppCss", ["/app.css"], "text/css; charset=utf-8"),
    ("app.js", "AppJs", ["/app.js"], "application/javascript; charset=utf-8"),
    ("favicon.svg", "Favicon", ["/favicon.svg"], "image/svg+xml"),
]

BYTES_PER_LINE = 16


def log(message):
    print("[gen_web_assets] " + message)


def gzip_bytes(raw):
    """Level 9, mtime 0, no stored filename - identical input, identical output."""
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0, filename="") as gz:
        gz.write(raw)
    return buf.getvalue()


def c_array_body(data):
    lines = []
    for start in range(0, len(data), BYTES_PER_LINE):
        chunk = data[start:start + BYTES_PER_LINE]
        lines.append("    " + " ".join("0x%02x," % b for b in chunk))
    return "\n".join(lines)


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_header(blobs):
    """blobs: list of (stem, served paths, content type, raw size, gzipped bytes)."""
    out = []
    w = out.append

    w("// GENERATED by firmware/tools/gen_web_assets.py - do not edit.")
    w("//")
    w("// The browser assets are gzipped into flash at build time so the GUI ships")
    w("// inside the firmware image. Edit the sources in web/ and rebuild (or rerun")
    w("// firmware/tools/gen_web_assets.py); any change made here is lost on the next")
    w("// build.")
    w("//")
    for stem, paths, _ctype, raw_len, gz in blobs:
        w("//   %-12s %6d B -> %6d B gzipped   %s" % (stem, raw_len, len(gz), " ".join(paths)))
    w("#pragma once")
    w("")
    w("#include <stddef.h>")
    w("#include <stdint.h>")
    w("#include <string.h>")
    w("")
    w("#include <pgmspace.h>")
    w("")
    w("namespace ep {")
    w("")
    w("// One row per servable path, holding everything a response needs. The blobs")
    w("// are pre-compressed, so the handler only has to promise Content-Encoding and")
    w("// hand the pointer to server.send_P.")
    w("struct WebAsset {")
    w("  const char*    path;")
    w("  const uint8_t* gzip;")
    w("  size_t         gzipLen;")
    w("  const char*    contentType;")
    w("};")
    w("")

    for stem, _paths, _ctype, _raw_len, gz in blobs:
        w("const uint8_t kWebAsset%sGz[] PROGMEM = {" % stem)
        w(c_array_body(gz))
        w("};")
        w("const size_t kWebAsset%sGzLen = sizeof(kWebAsset%sGz);" % (stem, stem))
        w("")

    w("const WebAsset kWebAssets[] = {")
    for stem, paths, ctype, _raw_len, _gz in blobs:
        for path in paths:
            w("    {%s, kWebAsset%sGz, kWebAsset%sGzLen, %s},"
              % (c_string(path), stem, stem, c_string(ctype)))
    w("};")
    w("const size_t kWebAssetCount = sizeof(kWebAssets) / sizeof(kWebAssets[0]);")
    w("")
    w("// Null for anything the firmware does not ship, which the 404 handler turns")
    w("// into a redirect to \"/\".")
    w("inline const WebAsset* findWebAsset(const char* path) {")
    w("  if (!path) return nullptr;")
    w("  for (size_t i = 0; i < kWebAssetCount; ++i) {")
    w("    if (strcmp(path, kWebAssets[i].path) == 0) return &kWebAssets[i];")
    w("  }")
    w("  return nullptr;")
    w("}")
    w("")
    w("}  // namespace ep")
    w("")
    return "\n".join(out)


def generate(web_dir, out_path):
    if not os.path.isdir(web_dir):
        log("WARNING: no web directory at %s" % web_dir)
        log("WARNING: keeping the existing %s (the GUI will be a placeholder page)"
            % os.path.basename(out_path))
        return False

    missing = [name for name, _s, _p, _c in ASSETS
               if not os.path.isfile(os.path.join(web_dir, name))]
    if missing:
        log("WARNING: %s is missing %s" % (web_dir, ", ".join(missing)))
        log("WARNING: keeping the existing %s rather than shipping half a GUI"
            % os.path.basename(out_path))
        return False

    blobs = []
    for name, stem, paths, ctype in ASSETS:
        with open(os.path.join(web_dir, name), "rb") as fh:
            raw = fh.read()
        blobs.append((stem, paths, ctype, len(raw), gzip_bytes(raw)))

    header = render_header(blobs)

    previous = None
    if os.path.isfile(out_path):
        try:
            with open(out_path, "r", encoding="utf-8") as fh:
                previous = fh.read()
        except OSError:
            previous = None
    if previous == header:
        log("%s is up to date" % out_path)
        return True

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
    total = sum(len(gz) for _s, _p, _c, _r, gz in blobs)
    log("wrote %s (%d B of gzipped assets)" % (out_path, total))
    return True


def project_dir_from_file():
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(argv):
    default_project = project_dir_from_file()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--web-dir", default=None,
                        help="directory holding index.html, app.css, app.js, favicon.svg "
                             "(default: <project>/../web)")
    parser.add_argument("--out", default=None,
                        help="header to write (default: <project>/src/app/web_assets.h)")
    args = parser.parse_args(argv)

    web_dir = args.web_dir or os.path.normpath(os.path.join(default_project, "..", "web"))
    out_path = args.out or os.path.join(default_project, "src", "app", "web_assets.h")
    generate(os.path.abspath(web_dir), os.path.abspath(out_path))
    return 0


# PlatformIO exec's this file with SCons' Import() in scope; plain python3 does
# not, which is how we tell the two apart.
_IS_PLATFORMIO = False
try:
    Import("env")  # noqa: F821  (injected by SCons)
    _IS_PLATFORMIO = True
except Exception:
    _IS_PLATFORMIO = False

if _IS_PLATFORMIO:
    _project = env.subst("$PROJECT_DIR")  # noqa: F821
    generate(os.path.abspath(os.path.join(_project, "..", "web")),
             os.path.abspath(os.path.join(_project, "src", "app", "web_assets.h")))
elif __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
