#!/usr/bin/env python3
"""Write src/app/build_stamp.h with the time of this build.

`/api/info` used to report `__DATE__ " " __TIME__` taken straight from
web_server.cpp. Those macros are expanded when that *one* translation unit is
compiled, so after a change to any other file -- store.cpp, ep_settings.cpp --
web_server.cpp is not rebuilt and the box keeps reporting the timestamp of some
earlier build. Two firmware images were flashed on 2026-11-02 and both reported
`Nov  1 2026 23:45:49`, which makes the single field you would check to confirm
a flash actively misleading.

So the stamp is generated here instead, and only build_stamp.cpp includes it.

Note the deliberate difference from gen_web_assets.py, which goes to some
trouble to rewrite its header *only* when the content changes, because
web_assets.h is included by web_server.cpp and rewriting it would rebuild a
large translation unit on every build. This header is the opposite case: it is
*meant* to change every time, and the only file that includes it is a dozen
lines long. Do not "fix" this to skip unchanged writes -- an unchanged write is
the bug.

Runs both ways, like its sibling:

  * as a PlatformIO pre-build script (``extra_scripts = pre:tools/...``);
  * as ``python3 firmware/tools/gen_build_stamp.py`` by hand.

Standard library only, Python 3.9 compatible: it runs inside PlatformIO's own
interpreter.
"""

import argparse
import datetime
import io
import os
import sys

HEADER = """// Generated by tools/gen_build_stamp.py on every build. Do not edit, and do not
// commit: the value is a property of one build on one machine.
#pragma once

#define EASYPILL_BUILD_STAMP "%s"
"""


def generate(out_path):
    # Local time, because the only question this answers is "is the board
    # running the thing I just built?" and the person asking is at the bench.
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with io.open(out_path, "w", encoding="utf-8") as f:
        f.write(HEADER % stamp)
    print("[gen_build_stamp] %s" % stamp)
    return stamp


def main(argv):
    here = os.path.dirname(os.path.abspath(__file__))
    default_project = os.path.normpath(os.path.join(here, ".."))

    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--out", help="path of the header to write")
    args = p.parse_args(argv)

    out_path = args.out or os.path.join(default_project, "src", "app", "build_stamp.h")
    generate(os.path.abspath(out_path))
    return 0


# PlatformIO exec's this file with SCons' Import() in scope; plain python3 does
# not, which is how we tell the two apart.
_IS_PLATFORMIO = False
try:
    Import("env")  # noqa: F821  (injected by SCons)
    _IS_PLATFORMIO = True
except Exception:
    _IS_PLATFORMIO = False

if _IS_PLATFORMIO:
    _project = env.subst("$PROJECT_DIR")  # noqa: F821
    generate(os.path.abspath(os.path.join(_project, "src", "app", "build_stamp.h")))
elif __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
